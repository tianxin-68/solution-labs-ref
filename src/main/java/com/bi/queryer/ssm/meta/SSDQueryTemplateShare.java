package com.bi.queryer.ssm.meta;

public class SSDQueryTemplateShare {
	
	private String tplId;
	
	private String shareUserName;
	
	private String sharedUserName;
	
	private String shareTime;
	
	private String sharedUserRealName;

	public String getTplId() {
		return tplId;
	}

	public void setTplId(String tplId) {
		this.tplId = tplId;
	}

	public String getShareUserName() {
		return shareUserName;
	}

	public void setShareUserName(String shareUserName) {
		this.shareUserName = shareUserName;
	}

	public String getSharedUserName() {
		return sharedUserName;
	}

	public void setSharedUserName(String sharedUserName) {
		this.sharedUserName = sharedUserName;
	}

	public String getShareTime() {
		return shareTime;
	}

	public void setShareTime(String shareTime) {
		this.shareTime = shareTime;
	}

	public String getSharedUserRealName() {
		return sharedUserRealName;
	}

	public void setSharedUserRealName(String sharedUserRealName) {
		this.sharedUserRealName = sharedUserRealName;
	}
}
